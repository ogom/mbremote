import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { toCSource } from "@microbit/ml4f";

import { REQUIRED_CONFIDENCE } from "./model-config.mjs";
import { loadModel } from "./model.mjs";
import { compileML4FModel } from "./verify-ml4f-model.mjs";

const PROJECT_DIRECTORY = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  ".."
);
const REPOSITORY_DIRECTORY = path.resolve(PROJECT_DIRECTORY, "..", "..", "..");
const OUTPUT_DIRECTORY = path.join(
  REPOSITORY_DIRECTORY,
  "packages",
  "mbremote",
  "support",
  "v2",
  "picoruby",
  "codal_app"
);
const SOURCE_PATH = path.join(OUTPUT_DIRECTORY, "magic_circle_model.c");
const HEADER_PATH = path.join(OUTPUT_DIRECTORY, "magic_circle_model.h");
const SYMBOL = "mbremote_magic_circle_model";

export function generateML4FArtifacts(model) {
  const compiled = compileML4FModel(model);
  const wordCount = compiled.machineCode.length / 4;
  const machineCode = toCSource(SYMBOL, compiled.machineCode).replace(
    /[ \t]+$/gm,
    ""
  );
  if (REQUIRED_CONFIDENCE.length !== Number(model.outputSize)) {
    throw new Error("PicoRuby confidence thresholds must match model outputs");
  }
  const confidenceValues = REQUIRED_CONFIDENCE
    .map((value) => `${value}f`)
    .join(", ");
  const source = `/*
 * Generated from examples/picoruby/magic-circle/data/model.json by
 * examples/picoruby/magic-circle/scripts/generate-ml4f-model.mjs.
 * Do not edit this file directly.
 *
 * SPDX-License-Identifier: MIT
 */

#include "magic_circle_model.h"

${machineCode}
const float mbremote_magic_circle_required_confidence[
    MBREMOTE_MAGIC_CIRCLE_MODEL_OUTPUTS
] = { ${confidenceValues} };

const float mbremote_magic_circle_minimum_gesture_motion =
    ${model.minimumGestureMotion}f;
`;
  const header = `/*
 * Generated from examples/picoruby/magic-circle/data/model.json by
 * examples/picoruby/magic-circle/scripts/generate-ml4f-model.mjs.
 * Do not edit this file directly.
 *
 * SPDX-License-Identifier: MIT
 */

#pragma once

#define MBREMOTE_MAGIC_CIRCLE_MODEL_WORDS ${wordCount}
#define MBREMOTE_MAGIC_CIRCLE_MODEL_ARENA_BYTES ${compiled.stats.total.arenaBytes}
#define MBREMOTE_MAGIC_CIRCLE_MODEL_OUTPUTS ${model.outputSize}

extern const unsigned mbremote_magic_circle_model[
    MBREMOTE_MAGIC_CIRCLE_MODEL_WORDS
];
extern const float mbremote_magic_circle_required_confidence[
    MBREMOTE_MAGIC_CIRCLE_MODEL_OUTPUTS
];
extern const float mbremote_magic_circle_minimum_gesture_motion;
`;
  return { source, header, compiled };
}

async function main() {
  const model = await loadModel();
  const artifacts = generateML4FArtifacts(model);
  await Promise.all([
    fs.writeFile(SOURCE_PATH, artifacts.source),
    fs.writeFile(HEADER_PATH, artifacts.header)
  ]);
  console.log(`generated: ${path.relative(process.cwd(), SOURCE_PATH)}`);
  console.log(`generated: ${path.relative(process.cwd(), HEADER_PATH)}`);
  console.log(`machine code: ${artifacts.compiled.machineCode.length} bytes`);
  console.log(
    `arena: ${artifacts.compiled.stats.total.arenaBytes} bytes`
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  await main();
}
