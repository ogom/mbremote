def _mean(values):
    return sum(values) / len(values)


def _stddev(values):
    average = _mean(values)
    total = 0
    for value in values:
        difference = value - average
        total += difference * difference
    return sqrt(total / len(values))


def _peaks(values):
    lag = 5
    filtered = list(values)
    average = _mean(values[:lag])
    deviation = average
    previous_signal = 0
    count = 0

    for index in range(lag, len(values)):
        difference = abs(values[index] - average)
        if difference > 0.1 and difference > 3.5 * deviation:
            signal = 1 if values[index] > average else -1
            if signal == 1 and previous_signal == 0:
                count += 1
            filtered[index] = 0.5 * (
                values[index] + filtered[index - 1]
            )
        else:
            signal = 0
            filtered[index] = values[index]

        window = filtered[index - lag:index]
        average = _mean(window)
        deviation = _stddev(window)
        previous_signal = signal

    return count


def _acceleration(values):
    total = 0
    for value in values:
        total += abs(value)
    return total * DEVICE_SAMPLES_LENGTH / len(values)


def _zero_crossing_rate(values):
    count = 0
    for index in range(1, len(values)):
        if (
            values[index] >= 0 and values[index - 1] < 0
        ) or (
            values[index] < 0 and values[index - 1] >= 0
        ):
            count += 1
    return count / (len(values) - 1)


def _rms(values):
    total = 0
    for value in values:
        total += value * value
    return sqrt(total / len(values))


def extract_features(x_values, y_values, z_values):
    if not x_values or not y_values or not z_values:
        raise ValueError()

    feature_values = []
    filters = (
        max,
        _mean,
        min,
        _stddev,
        _peaks,
        _acceleration,
        _zero_crossing_rate,
        _rms,
    )
    for strategy in filters:
        feature_values.append(strategy(x_values))
        feature_values.append(strategy(y_values))
        feature_values.append(strategy(z_values))
    return feature_values


def predict(feature_values):
    if len(feature_values) != INPUT_SIZE:
        raise ValueError()

    hidden = [0] * HIDDEN_SIZE
    for hidden_index in range(HIDDEN_SIZE):
        value = HIDDEN_BIAS[hidden_index]
        weight_index = hidden_index
        for feature in feature_values:
            value += feature * INPUT_WEIGHTS[weight_index]
            weight_index += HIDDEN_SIZE
        hidden[hidden_index] = value if value > 0 else 0

    logits = [0] * OUTPUT_SIZE
    for output_index in range(OUTPUT_SIZE):
        value = OUTPUT_BIAS[output_index]
        weight_index = output_index
        for hidden_value in hidden:
            value += hidden_value * OUTPUT_WEIGHTS[weight_index]
            weight_index += OUTPUT_SIZE
        logits[output_index] = value

    maximum = max(logits)
    total = 0
    for index in range(OUTPUT_SIZE):
        probability = exp(logits[index] - maximum)
        logits[index] = probability
        total += probability

    best_index = 0
    best_delta = -2
    for index in range(OUTPUT_SIZE):
        confidence = logits[index] / total
        logits[index] = confidence
        delta = confidence - REQUIRED_CONFIDENCE[index]
        if delta > best_delta:
            best_index = index
            best_delta = delta

    return best_index, logits[best_index]


def is_confident(action_index, confidence, feature_values):
    if confidence < REQUIRED_CONFIDENCE[action_index]:
        return False
    if action_index <= 2:
        motion = max(feature_values[9:12])
        return motion >= MIN_GESTURE_MOTION
    return True
